# gunicorn은 시작 명령(`gunicorn app:app`)에 -c가 없어도 실행 폴더의 이 파일을 자동으로 읽는다(Procfile의 옵션은 Cloudtype에서 적용되지 않았다).
#
# 왜 필요한가: 예전 설정은 워커 1개·동기 방식이라 요청을 한 번에 하나씩만 처리했다. 법정 의무 마스터 화면이 파트를 5개 동시에 보내면
# 나머지가 줄을 서서 기다리다 Cloudtype 게이트웨이 제한(60초)에 걸려 504가 났다(운영 확인: 5개 동시 요청 중 3개가 61초에 504).
# Gemini·법제처 호출은 대부분 기다리는 시간이라 스레드로 겹쳐 처리하면 된다.
#
# 워커는 1개로 둔다: 작업 목록(JOBS)과 후속 채팅 기억(qa_grounding)이 프로세스 메모리에 있어서 워커를 늘리면 서로 못 본다.
# (그래서 요청 처리량은 스레드로 늘린다.)
worker_class = "gthread"
workers = 1
threads = 8
timeout = 120          # 스레드 방식에서는 느린 요청 하나가 워커 전체를 죽이지 않지만, 멈춘 워커를 되살리는 기준은 남겨 둔다
graceful_timeout = 30
