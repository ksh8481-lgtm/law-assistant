def find_jurisdiction_in_text(text: str) -> str:
    """텍스트 전체(잘라내지 않음)에서 실제 존재하는 지자체명을 찾아 반환한다.

    가장 먼저(텍스트 상 앞쪽에) 등장하는 기초자치단체명을 우선 반환하고,
    기초자치단체가 하나도 없으면 광역자치단체명이라도 반환한다. 하나도
    없으면 빈 문자열.
    """
    if not text:
        return ""

    best_name = ""
    best_pos = len(text) + 1

    for name in BASIC_REGIONS:
        pos = text.find(name)
        if pos != -1 and pos < best_pos:
            best_pos = pos
            best_name = name

    if best_name:
        return best_name

    for name in METROPOLITAN_REGIONS:
        pos = text.find(name)
        if pos != -1 and pos < best_pos:
            best_pos = pos
            best_name = name

    return best_name
